#!/bin/bash
# setup_iptables.sh: prints templates/ip_rules_v4.txt (or ip_rules_v6.txt with --v6) with
# %%SSH_PORT%% replaced by the sshd port, for iptables-restore / ip6tables-restore (#146).
# It only prints. It never applies the rules and never runs sudo, iptables* or netfilter-persistent:
# changing the firewall can lock you out of the VPS (P1 / P14), so applying stays a manual step done
# with the current ssh session kept open (see the hints printed on stderr and the Wiki setup_iptables).
# common.sh is not read: it would create ~/.atst/config, and nothing here needs it.
# stdout: the rules only (a "# Generated by ..." line first), printed once at the end, so that
#   "> rules.v4" never gets a partial file. Warnings, hints and errors go to stderr.
# Exit codes: 0 printed (also with warnings), 1 wrong arguments, 2 broken template (nothing printed).

setup_iptables_usage() {
  echo "Usage: setup_iptables.sh [--port <sshd port>] [--v6]"
  echo "  prints the iptables rules of templates/ip_rules_v4.txt (--v6: ip_rules_v6.txt) with"
  echo "  %%SSH_PORT%% replaced by <sshd port> (1-65535, default 22). Nothing is applied."
  echo "  Check the port with: sudo sshd -T | grep -i '^port '"
}

port=22
port_given=0
family=v4
while [ "$#" -gt 0 ]; do
  case "$1" in
    -h|--help)
      setup_iptables_usage
      exit 0
      ;;
    --port)
      if [ "$#" -lt 2 ]; then
        setup_iptables_usage >&2
        exit 1
      fi
      port=$2
      port_given=1
      shift 2
      ;;
    --v6)
      family=v6
      shift
      ;;
    *)
      setup_iptables_usage >&2
      exit 1
      ;;
  esac
done

if ! [[ "$port" =~ ^[1-9][0-9]{0,4}$ ]] || [ "$port" -gt 65535 ]; then
  setup_iptables_usage >&2
  exit 1
fi

tmpl_name="ip_rules_$family.txt"
tmpl="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/templates/$tmpl_name"

# Comment lines keep their %%SSH_PORT%% (they explain it); only rule lines are replaced.
if ! rendered=$(sed -e '/^[[:space:]]*#/!s/%%SSH_PORT%%/'"$port"'/g' "$tmpl" 2>/dev/null) || [ -z "$rendered" ]; then
  echo "[error] the template is missing or empty: templates/$tmpl_name" >&2
  exit 2
fi

# A rule line still holding %% or anything but exactly one rule for the port means the template is
# broken: print nothing (iptables-restore given an empty input changes nothing).
rules=$(printf '%s\n' "$rendered" | sed -e '/^[[:space:]]*#/d')
if [[ "$rules" == *%%* ]]; then
  echo "[error] templates/$tmpl_name has a placeholder left on a rule line" >&2
  exit 2
fi
ssh_rules=$(printf '%s\n' "$rules" | grep -cF -- "--dport $port ")
if [ "$ssh_rules" != 1 ]; then
  echo "[error] templates/$tmpl_name should have exactly one rule for port $port, found $ssh_rules" >&2
  exit 2
fi

# Reachability hints (read only; they never change the exit code).
if [ "$port_given" -eq 0 ]; then
  echo "[warn] --port not given: port 22 is assumed. Check: sudo sshd -T | grep -i '^port '" >&2
fi
if command -v ss >/dev/null 2>&1 && ! ss -tln 2>/dev/null | grep -qE "[:.]${port}[[:space:]]"; then
  echo "[warn] nothing is listening on TCP port $port; check that it is the sshd port (sudo sshd -T | grep -i '^port ') or you will be locked out." >&2
fi

printf '%s\n' "# Generated by setup_iptables.sh --port $port from templates/$tmpl_name" "$rendered"

if [ "$family" = v6 ]; then
  ipt=ip6tables
else
  ipt=iptables
fi
{
  echo "[info] Nothing has been applied. To apply the rules printed above:"
  echo "  1. save them to a file (e.g. setup_iptables.sh ... > rules.$family)"
  echo "  2. sudo $ipt-restore --test < rules.$family  (if it fails, e.g. hashlimit is not supported, do not apply)"
  echo "  3. keep the current ssh session open and run: sudo $ipt-restore < rules.$family"
  echo "  4. from another terminal, check that a new ssh connection to port $port works, and only then make it permanent"
  echo "  The HTTP/HTTPS lines stay commented out; remove their '#' only when a public web site runs on this VPS."
  echo "  Details: Wiki setup_iptables"
} >&2
